export interface Run { x: number; y: number; w: number }

/** Horizontal pixel runs for `text`, in font pixels (also used by PixelScene's title) */
export function layoutPixelText(text: string): { runs: Run[]; width: number; rows: number } {
  const runs: Run[] = []
  let cursor = 0
  const chars = [...text]
    .map(ch => (FONT[ch] ? ch : FONT[ch.toUpperCase()] ? ch.toUpperCase() : ''))
    .filter(Boolean)
  // Mixed-case text always reserves the descender row so stacked lines keep an even rhythm
  const rows = Math.max(chars.some(ch => ch >= 'a' && ch <= 'z') ? 8 : 7, ...chars.map(ch => FONT[ch].length))
  chars.forEach((ch, i) => {
    const glyph = FONT[ch]
    glyph.forEach((row, y) => {
      let start = -1
      for (let x = 0; x <= row.length; x++) {
        const on = row[x] === '#'
        if (on && start < 0) start = x
        if (!on && start >= 0) {
          runs.push({ x: cursor + start, y, w: x - start })
          start = -1
        }
      }
    })
    cursor += glyph[0].length + (i < chars.length - 1 ? 1 : 0)
  })
  return { runs, width: cursor, rows }
}

interface Props {
  text: string
  /** Screen pixels per font pixel — keep it an integer for crisp edges */
  scale?: number
  /** Solid fill, or a list of colors banded top→bottom across the 7 rows */
  color?: string | string[]
  /** Drop shadow color (offset one font pixel down-right) */
  shadow?: string
  className?: string
  title?: string
}

export const PixelText = memo(function PixelText({
  text, scale = 3, color = 'currentColor', shadow, className, title,
}: Props) {
  const id = useId().replace(/:/g, '')
  const { runs, width, rows } = layoutPixelText(text)
  const pad = shadow ? 1 : 0
  const vw = width + pad
  const vh = rows + pad
  const bands = Array.isArray(color) ? color : null
  const fill = bands ? `url(#pt-${id})` : (color as string)

  return (
    <svg
      className={className}
      width={vw * scale}
      height={vh * scale}
      viewBox={`0 0 ${vw} ${vh}`}
      shapeRendering="crispEdges"
      role={title ? 'img' : undefined}
      aria-label={title ?? text}
    >
      {bands && (
        <defs>
          <linearGradient id={`pt-${id}`} x1="0" y1="0" x2="0" y2={rows} gradientUnits="userSpaceOnUse">
            {bands.flatMap((c, i) => [
              <stop key={`${i}a`} offset={i / bands.length} stopColor={c} />,
              <stop key={`${i}b`} offset={(i + 1) / bands.length} stopColor={c} />,
            ])}
          </linearGradient>
        </defs>
      )}
      {shadow && (
        <g fill={shadow} transform="translate(1 1)">
          {runs.map((r, i) => <rect key={i} x={r.x} y={r.y} width={r.w} height={1} />)}
        </g>
      )}
      <g fill={fill}>
        {runs.map((r, i) => <rect key={i} x={r.x} y={r.y} width={r.w} height={1} />)}
      </g>
    </svg>
  )
})
